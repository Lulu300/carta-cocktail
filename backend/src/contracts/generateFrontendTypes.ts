import { writeFileSync } from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';
import ts from 'typescript';
import * as contracts from './frontendTypes';

/*
 * Writes frontend/src/types/generated.ts from frontendTypes.ts (task F-05). The TypeScript
 * compiler infers each exported alias (`z.output<typeof Schema>`), and the inferred type is
 * printed as plain TypeScript: the frontend needs neither zod nor the backend sources. A
 * nested type that is itself exported is printed by its name.
 */

const BACKEND_DIR = path.resolve(__dirname, '../..');
const CONTRACTS_FILE = path.join(__dirname, 'frontendTypes.ts');
export const GENERATED_FILE = path.resolve(BACKEND_DIR, '../frontend/src/types/generated.ts');

const HEADER = `// Generated by \`npm run contracts:generate\` (backend/src/contracts/generateFrontendTypes.ts)
// from the zod schemas listed in backend/src/contracts/frontendTypes.ts. Do not edit:
// change the schemas, then generate again.
`;

function loadProgram(): ts.Program {
  const configPath = path.join(BACKEND_DIR, 'tsconfig.json');
  const { config } = ts.readConfigFile(configPath, (file) => ts.sys.readFile(file));
  const { options } = ts.parseJsonConfigFileContent(config, ts.sys, BACKEND_DIR);
  return ts.createProgram([CONTRACTS_FILE], options);
}

function exportedTypeAliases(program: ts.Program, fileName: string): ts.Symbol[] {
  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(fileName);
  const moduleSymbol = sourceFile && checker.getSymbolAtLocation(sourceFile);
  if (!moduleSymbol) throw new Error(`Cannot read ${fileName}`);
  return checker
    .getExportsOfModule(moduleSymbol)
    .filter((symbol) => symbol.flags & ts.SymbolFlags.TypeAlias);
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** Prints a type the compiler inferred, using the exported names of the types it contains. */
class TypePrinter {
  /**
   * Exported unions by their printed text. The compiler infers `z.input` and `z.output` of the
   * same enum as two distinct types: the text finds the name of either.
   */
  private readonly unionNames = new Map<string, string>();

  constructor(
    private readonly checker: ts.TypeChecker,
    private readonly names: Map<ts.Type, string>,
  ) {
    for (const [type, name] of names) {
      if (type.isUnion()) this.unionNames.set(this.printUnion(type.types), name);
    }
  }

  /** `asDeclaration`: the type of an exported alias, printed in full rather than by its name. */
  print(type: ts.Type, asDeclaration = false): string {
    const name = this.names.get(type);
    if (name && !asDeclaration) return name;
    if (type.isUnion()) {
      const printed = this.printUnion(type.types);
      return asDeclaration ? printed : this.nameOfUnion(printed);
    }
    if (type.isStringLiteral()) return JSON.stringify(type.value);
    if (type.isNumberLiteral()) return String(type.value);
    const intrinsic = this.printIntrinsic(type);
    if (intrinsic) return intrinsic;
    if (this.checker.isArrayType(type)) return this.printArray(type);
    if (type.flags & ts.TypeFlags.Object && type.getCallSignatures().length === 0) {
      return this.printObject(type);
    }
    throw new Error(`Unsupported type: ${this.checker.typeToString(type)}`);
  }

  private printIntrinsic(type: ts.Type): string | null {
    const { flags } = type;
    if (flags & ts.TypeFlags.String) return 'string';
    if (flags & ts.TypeFlags.Number) return 'number';
    if (flags & ts.TypeFlags.Boolean) return 'boolean';
    if (flags & (ts.TypeFlags.BooleanLiteral | ts.TypeFlags.Null | ts.TypeFlags.Undefined)) {
      return this.checker.typeToString(type);
    }
    if (flags & (ts.TypeFlags.Unknown | ts.TypeFlags.Any)) return 'unknown';
    return null;
  }

  private nameOfUnion(printed: string): string {
    return this.unionNames.get(printed) ?? printed;
  }

  private printUnion(members: readonly ts.Type[]): string {
    const printed = members.map((member) => this.print(member));
    // The compiler splits `boolean` into its two literals
    const hasBoolean = printed.includes('true') && printed.includes('false');
    const merged = hasBoolean
      ? printed
          .map((text) => (text === 'true' ? 'boolean' : text))
          .filter((text) => text !== 'false')
      : printed;
    // `string | null` reads better than the compiler's internal order
    const isEmpty = (text: string) => text === 'null' || text === 'undefined';
    return [...merged.filter((text) => !isEmpty(text)), ...merged.filter(isEmpty)].join(' | ');
  }

  private printArray(type: ts.Type): string {
    const [element] = this.checker.getTypeArguments(type as ts.TypeReference);
    const printed = this.print(element);
    return element.isUnion() && !this.names.has(element) ? `(${printed})[]` : `${printed}[]`;
  }

  private printObject(type: ts.Type): string {
    const properties = this.checker.getPropertiesOfType(type);
    const [index, ...otherIndexes] = this.checker.getIndexInfosOfType(type);
    if (properties.length === 0 && index && otherIndexes.length === 0) {
      return `Record<${this.print(index.keyType)}, ${this.print(index.type)}>`;
    }
    if (index) throw new Error(`Unsupported index signature: ${this.checker.typeToString(type)}`);
    const lines = properties.map((property) => this.printProperty(property));
    return `{\n${lines.join('\n')}\n}`;
  }

  private printProperty(property: ts.Symbol): string {
    const isOptional = (property.flags & ts.SymbolFlags.Optional) !== 0;
    const type = this.checker.getTypeOfSymbol(property);
    // An optional property's type includes `undefined`: `?` already says it
    const printed =
      isOptional && type.isUnion()
        ? this.nameOfUnion(
            this.printUnion(
              type.types.filter((member) => !(member.flags & ts.TypeFlags.Undefined)),
            ),
          )
        : this.print(type);
    const key = IDENTIFIER.test(property.name) ? property.name : JSON.stringify(property.name);
    const doc = ts.displayPartsToString(property.getDocumentationComment(this.checker));
    const comment = doc ? `/** ${doc.replace(/\s*\n\s*/g, ' ')} */\n` : '';
    return `${comment}${key}${isOptional ? '?' : ''}: ${printed};`;
  }
}

function printConstants(): string[] {
  // Sorted: the order of a module's exports depends on the loader (tsx or Vitest)
  const entries = Object.entries(contracts).sort(([a], [b]) => a.localeCompare(b));
  return entries.map(
    ([name, value]) => `export const ${name} = ${JSON.stringify(value)} as const;`,
  );
}

/** One declaration per type alias exported by the file, in the order of the file. */
export function printTypeAliases(program: ts.Program, fileName: string): string[] {
  const checker = program.getTypeChecker();
  const aliases = exportedTypeAliases(program, fileName).map((symbol) => ({
    name: symbol.name,
    type: checker.getDeclaredTypeOfSymbol(symbol),
  }));
  const names = new Map(aliases.map(({ name, type }) => [type, name]));
  const printer = new TypePrinter(checker, names);
  return aliases.map(({ name, type }) => `export type ${name} = ${printer.print(type, true)};`);
}

/** The content of the generated file, formatted with the repository's Prettier settings. */
export async function generateFrontendTypes(): Promise<string> {
  const declarations = printTypeAliases(loadProgram(), CONTRACTS_FILE);
  const source = [HEADER, ...printConstants(), ...declarations].join('\n\n');
  const options = await prettier.resolveConfig(GENERATED_FILE);
  return prettier.format(source, { ...options, parser: 'typescript' });
}

async function main() {
  writeFileSync(GENERATED_FILE, await generateFrontendTypes());
  console.log(`Wrote ${path.relative(process.cwd(), GENERATED_FILE)}`);
}

if (require.main === module) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
